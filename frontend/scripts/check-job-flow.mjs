import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const source = readFileSync(new URL("../src/App.svelte", import.meta.url), "utf8");
const setup = readFileSync(new URL("../src/components/SetupView.svelte", import.meta.url), "utf8");
const live = readFileSync(new URL("../src/components/LiveView.svelte", import.meta.url), "utf8");
const dashboard = readFileSync(new URL("../src/components/DashboardView.svelte", import.meta.url), "utf8");
const api = readFileSync(new URL("../src/lib/api.ts", import.meta.url), "utf8");
const media = readFileSync(new URL("../src/lib/media.ts", import.meta.url), "utf8");
const publisher = readFileSync(new URL("../src/lib/mediamtx-publisher.js", import.meta.url), "utf8");
const styles = readFileSync(new URL("../src/app.css", import.meta.url), "utf8");
const create = source.slice(source.indexOf("async function handleCreate"), source.indexOf("async function handlePublishStart"));
const publish = source.slice(source.indexOf("async function handlePublishStart"), source.indexOf("function startStatsPolling"));

assert.match(create, /await probeVideoCodecs\(input\.width, input\.height, input\.fps\)/, "Create must validate the output encoder profile");
assert.match(create, /await createStream\(/, "Create must allocate the server job");
assert.ok(create.indexOf("await probeVideoCodecs(") < create.indexOf("await createStream("), "Output validation must happen before the server job is created");
assert.doesNotMatch(create, /await handlePublishStart\(\)/, "Creating a job must not open the camera automatically");
assert.match(setup, /probeCameraProfiles\(/, "Setup must probe exact camera modes");
assert.match(setup, /probeVideoCodecs\(width, height, targetFps\)/, "Setup must probe the selected encoder profile");
assert.match(setup, /profileSupported/, "Create must stay disabled until the selected camera mode passes");
assert.match(setup, /outputSupported !== true/, "Create must stay disabled until the selected encoder profile passes");
assert.match(publish, /await openValidatedCapture\(/, "Every relay start must revalidate the selected profile");
assert.match(publish, /await updateStream\(/, "Relay start must persist profile changes without replacing the job");
assert.match(source, /async function stopRelay\(\)/, "Stopping relay must update the persistent server job");
assert.match(source, /async function leaveLive\(\)/, "Leaving live view must return to the dashboard without deleting the job");
assert.match(api, /export const deleteStream/, "The API must expose explicit stream deletion");
assert.match(dashboard, /onDeleteStream/, "The dashboard must expose explicit stream deletion");
assert.match(dashboard, /on:click=\{\(\) => onOpenStream\(stream\)\}/, "Stopped jobs must remain reopenable");
assert.match(live, /onLeaveHome/, "Live view must provide a reusable Home action");
assert.match(media, /frameRate: \{ exact: profile\.fps \}/, "Camera FPS must be selected with an exact constraint");
assert.doesNotMatch(media, /captureStream\(/, "The camera path must not create a canvas capture stream");
assert.doesNotMatch(media, /document\.createElement\("canvas"\)/, "The camera path must not create a canvas");
assert.match(media, /codedWidth/, "Source frame dimensions must be verified before publishing");
assert.match(media, /maxWidth/, "Camera capability details must include maximum dimensions");
assert.doesNotMatch(media, /setPortraitMode/, "The capture session must not expose live framing changes");
assert.match(live, /preview-video/, "Live preview must expose the real camera source");
assert.match(live, /source-landscape/, "Mobile preview orientation must come from source dimensions");
assert.match(live, /preview-stage/, "Live view must have a dedicated preview stage");
assert.match(styles, /body:has\(\.live-page\)/, "Mobile live view must disable page scrolling");
assert.match(styles, /object-fit: cover/, "Mobile source preview must fill its portrait stage");
assert.match(styles, /100cqh/, "Mobile landscape source preview must scale from the full stage");
assert.match(styles, /rotate\(-90deg\)/, "Mobile landscape preview must place the right side at the top");
assert.match(publisher, /let writeQueue = Promise\.resolve\(\)/, "Encoded subgroups must be serialized per track");
assert.match(publisher, /const transport = this\.#wt/, "Encoded writes must stay tied to their connection");
assert.match(publisher, /this\.#writeData\(\s*transport,/, "Encoded subgroups must use the captured transport");
assert.doesNotMatch(publisher, /fetch\(this\.#conf\.fingerprintUrl, \{\s*headers:/, "Fingerprint fetch must not send Authorization and trigger CORS preflight");

